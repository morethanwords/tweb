// The production allowlist is generated offline, never from request data.
const fs = require('node:fs');
const path = require('node:path');
const names = ['pluto', 'venus', 'aurora', 'vesta', 'flora'];
const routes = [];
for(let dc = 1; dc <= 5; dc++) {
  for(const suffix of ['', '-1']) {
    for(const test of [false, true]) {
      if(test && dc > 3) continue;
      for(const ws of [true, false]) {
        const host = (ws ? `kws${dc}` : names[dc - 1]) + suffix;
        const endpoint = ws ? `apiws${test ? '_test' : ''}` : `apiw${test ? '_test1' : '1'}`;
        routes.push({path: `/mtproto/${host}/${endpoint}`, host: `${host}.web.telegram.org`, endpoint: `/${endpoint}`, method: ws ? 'GET' : 'POST'});
      }
    }
  }
}
module.exports = routes;
if(require.main === module) {
  const output = '# Generated by node deploy/generate-routes.cjs; do not edit.\n' +
    routes.map((r, i) => `import telegram ${r.path} ${r.host} ${r.endpoint} ${r.method} ${i}`).join('\n') + '\n';
  const target = path.join(__dirname, 'relay-routes.caddy');
  if(process.argv.includes('--check')) {
    if(fs.readFileSync(target, 'utf8') !== output) throw new Error('Relay routes are stale');
  } else fs.writeFileSync(target, output);
}
